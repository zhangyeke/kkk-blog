/**
 * 后台菜单树的内置种子（39 行）。
 *
 * 书签为多级结构（id 5 书签管理 → 33 书签 / 34 书签分类），
 * 现有库由 `006_bookmark_menu_tree.sql` 从 005 的 32 行扁平结构升级而来。
 *
 * ── 为什么代码里还要再抄一份 SQL 种子 ──
 *
 * prisma/manual-sql/005_seed_admin_menu.sql + 006 是**落库**用的；
 * 这份 TS 常量是**降级**用的：
 * - 表还没建 / 连接失败 / Prisma 客户端没重新生成 / 菜单表为空时，导航和可用权限 key 仍能工作；
 * - 供迁移和离线测试使用；默认角色授权由 permissions.ts 的 DEFAULT_PERMISSION_MATRIX 提供。
 *
 * 菜单/权限读取优先使用数据库；数据库不可用时，服务端导航与页面守卫使用这份菜单种子和默认授权。
 *
 * ⚠️ 本文件保持 **Edge 安全**：不 import "server-only"，不 import Prisma。
 * 与 005 + 006 SQL 的最终结构逐字段一致 —— 改一边必须同步改另一边。
 */

import { type AdminMenuNode, buildMenuTree, buildPathIndex, type PathPermissionEntry } from "@/lib/menu-tree"

/** 节点类型：目录 / 菜单 / 按钮 */
export type MenuType = "dir" | "menu" | "button"

/**
 * 一行菜单（不含 createdAt / updatedAt）。
 *
 * 特意不带时间字段：种子是常量，写死时间只会让「降级数据」和「库里数据」在
 * 版本号 / 比对时产生无意义的差异。
 */
export type AdminMenuRow = {
  id: number
  parentId: number | null
  name: string
  type: MenuType
  icon: string | null
  path: string | null
  component: string | null
  componentName: string | null
  /** 权限判定唯一标识：page:* / action:*；目录为 null */
  permissionKey: string | null
  sort: number
  /** 0：停用 1：正常 */
  status: number
  /** 是否在侧栏显示（false = 有权限但藏起来，例如详情页） */
  visible: boolean
  /** 只有一个子项时是否仍显示父级 */
  alwaysShow: boolean
  /** 前端缓存页面状态（预留给 T03） */
  keepAlive: boolean
  /** 内置行：不可删除 */
  isBuiltin: boolean
}

